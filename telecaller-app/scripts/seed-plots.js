// Helper to generate dynamic plot object with serialized points
function makePlot(id, number, size, rate, status, points) {
  const numericSize = parseFloat(size);
  const numericRate = parseFloat(rate);
  const priceVal = isNaN(numericSize) || isNaN(numericRate) ? "" : (numericSize * numericRate).toLocaleString('en-IN');
  return {
    id: id.toString(),
    number: number.toString(),
    size: size.toString(),
    rate: rate.toString(),
    price: priceVal,
    status: status,
    // Convert [[x, y]] to [{x, y}] to avoid nested arrays in Firestore
    points: points.map(pt => ({ x: pt[0], y: pt[1] }))
  };
}

